function f=p2f(p,a,b,c,xl) % mm -> kHz
f = a * (10.^ (b * (1 - p / xl) * 100) - c);
return
end

function p=f2p(f,a,b,c,xl) % kHz -> mm
p = (1 - (log10((f / a) + c) / b) / 100) * xl;
return
end

